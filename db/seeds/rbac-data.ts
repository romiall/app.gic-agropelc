function grants(
  roleCode: string,
  entries: ReadonlyArray<readonly [string, string, Record<string, unknown>?]>,
): RolePermissionSeed[] {
  return entries.map(([permissionCode, maxScope, limits]) =>
    limits
      ? { roleCode, permissionCode, maxScope, limits }
      : { roleCode, permissionCode, maxScope },
  );
}


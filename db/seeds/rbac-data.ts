/**
 * Matrice RBAC (source : docs/07-security-rbac/01-rbac.md §5, §8 ; docs/01-functional/
 * 04-acteurs-et-roles.md §2 ; ADR-008). Devient, une fois ce fichier livré, la source de
 * vérité courante de la matrice (docs/10-development-plan/05-audit-coherence.md, DT-07) :
 * une évolution de portée ou d'octroi se fait ici, pas dans une migration ni dans le
 * markdown source, qui reste la trace de la décision initiale (§9 de 01-rbac.md : « tests
 * générés depuis la matrice », pas l'inverse).
 *
 * Statuts (00-reference/00-conventions.md §2) :
 * - CONFIRMÉ : codes de permission, max_scope et limits par (rôle, permission), is_approval
 *   (préfixe `A·` de la matrice), les 11 rôles eux-mêmes — lecture directe de 01-rbac.md.
 * - DÉDUIT : `allowedScopeTypes` par rôle (jamais publié comme tableau littéral — déduit du
 *   type de périmètre des affectations données en exemple, 01-rbac.md §8) ; `supportedScopes`
 *   par permission (union des portées effectivement accordées à au moins un rôle dans la
 *   matrice — un minorant reproductible, pas une liste indépendamment publiée) ; les
 *   descriptions (libellés courts, la matrice ne documente que codes/portées/limits).
 * - À VALIDER : `isSensitive` — AV-092, `false` partout (aucune permission désignée par une
 *   source ; défaut du schéma). `RESP_PRODUCTION.finance.expense.approve.limits` — AV-058
 *   (montant non chiffré dans la matrice pour ce rôle précisément) : accordé sans `limits`.
 *   `attachments.attachment.manage` — AV-093 (permission générique, portée OWN pour les 11
 *   rôles : « Permission de l'opération » de SM-ATTACHMENT n'est pas résolvable avant qu'un
 *   module propriétaire, P2+, n'existe).
 *
 * Rôles proposés mais non créés (AV-004, OUVERT) : OPERATEUR_FERME, LIVREUR, CAISSIER —
 * volontairement absents de ROLES.
 */

export interface RoleSeed {
  readonly code: string;
  readonly name: string;
  readonly description: string;
  readonly allowedScopeTypes: readonly string[];
}

export interface PermissionSeed {
  readonly code: string;
  readonly module: string;
  readonly description: string;
  readonly supportedScopes: readonly string[];
  readonly isApproval: boolean;
  readonly isSensitive: boolean;
}

export interface RolePermissionSeed {
  readonly roleCode: string;
  readonly permissionCode: string;
  readonly maxScope: string;
  readonly limits?: Record<string, unknown>;
}

export interface RoleDiscountSetting {
  readonly key: string;
  readonly value: number;
  readonly ref: string;
}

